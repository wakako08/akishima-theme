    <p><strong>（ホームページの運用）</strong><br>
    第15条　本会や加盟自治会の諸会合、行事等の概要を随時投稿し、現在取り組んでいる課題やこれから取り組むことの情報内容を発信し、自治会活動の情報を提供する。<br>
    １　サイト全体の管理運営責任者は会長とし加盟自治会のサイトは自治会長とする。<br>
    ２　投稿は自治連全体のものと、希望する加盟自治会が随時できるようにブログ方式とする。<br>
    ３　加盟自治会の情報でも、会長が必要と思うものに関しては、本会本体の方に投稿する場合もある。<br>
    ４　ブログ投稿研修や日常運営に協力いただける協力者を若干名、会長の承認でおく。<br>
    ５　投稿で、ふさわしくない内容の際は、本会会長の判断で削除する。<br>
    ６　加盟自治会のブログ投稿に対し、本会として研修会等を設け支援し、状況によっては期間を限定し投稿の応援をおこなうことができる。<br>
    ７　加盟自治会のブログ担当者には自治会長の依頼で"ＩＤとパスワード"を個別に発行し担当者から外れる場合は、必ず会長から報告をすることとする。<br>
    ８　希望するブロックやコミュニティ協議会のサイトを、加盟自治会と同じレベルで、常任委員会の承認で設けることができる。<br>
    ９　ホームページの運営費用は、市内の各種店舗紹介をバナーで有料紹介し広告協賛費として協力いただき、運営費用を賄えるよう役員全員で協賛店舗を増やす。<br>
    10　広告宣伝費の年間契約期間は、原則４月１日から翌年の３月末日とする。</p>
    <p><strong>（会員特典制度の運用）</strong><br>
    第16条　自治会員の加入率向上と、会員へのサービスの為、昭島市を中心に各種企業・店舗の協力により、平成２７年４月から実施する。<br>
    １　会員証は、自治会連合会が作成し、加盟自治会に会員数配布する。<br>
    ２　再発行は、加盟自治会で行う。<br>
    ３　会員証裏面上の登録番号６桁は、初めの２桁がブロックの番号で後の４桁が、ブロック内の通し番号で、登録番号を登録管理するか、しないは加盟自治会に任せる。<br>
    ４　利用は会員及び家族のみで、未会員への譲渡・貸与は禁止。退会時返却いただく。<br>
    ５　協力店の申込みは随時行う。<br>
    ６　自治連のホームページで、特典制度の説明、協力店＆サービス内容を随時更新する。<br>
    ７　協力店には、店頭用のぼりやレジ用ミニのぼり、店内用協力店証等を提供する。<br>
    ８　サービス内容は協力店に一任し、変更の際は連絡いただき、一覧を修正する。</p>
    <p><strong>（東京都地域の底力発展事業助成の活用）</strong><br>
    第17条　助成金活用の際、「交付申請書」「事業計画書」「収支予算書」を作成し、常任委員会で承認後、東京都に申請し活用するものとする。</p>
    <p><strong>（不動産業界との協定書の締結）</strong><br>
    第18条　不動産業界との相互の協力を図り、本会とが連携のもと、会員増強と住みよい環境をつくるため、相互に協力し、地域社会の発展に寄与することを目的として、協定書を次の２団体と締結する。<br>
    公益社団法人東京都宅地建物取引業協会　立川支部<br>
    公益社団法人全日本不動産協会東京都本部　多摩西支部</p>
    <p><strong>（個人情報取扱規程）</strong><br>
    第19条　この取扱方法は、本会が保有する個人情報の適切な取り扱いを定めることにより事業の円滑な運営を図るとともに、個人の権利利益を保護することを目的とする。<br>
    ２　本会は個人情報保護に関する法令等を厳守すると共に、自治会連合会活動において個人情報の保護に努めるものとする。<br>
    ３　個人情報取り扱いの方法は総会資料等で、加盟自治会に周知する。<br>
    ４　前条の個人情報とは、加盟自治会から提出された次の事項を記したものとする。<br>
    　氏名・住所・電話番号・その他の事項<br>
    ５　当会への加盟を退会する申し出があった場合は、直ちに該当する個人情報を廃棄、または削除しなければならない。ただし、既に加盟自治会等に配布しているものに対しては削除の連絡をすることでこれに替える。<br>
    ６　取得した個人情報は、次の目的に沿った利用を行うものとする。<br>
    　自治会連合会会員名簿の作成<br>
    　緊急時・災害時などの連絡網の作成<br>
    　管理、その他広報を始め文書のお届け等<br>
    ７　個人情報は会長または、自治連事務局が適切に管理する。<br>
    (２) 不要となった個人情報は会長立会いのもと、適正に廃棄するものとする。<br>
    ８　個人情報は次に挙げる場合を除き、あらかじめ本人の同意を得ないで第三者に提供しない。<br>
    (１) 法令に基づく場合<br>
    (２) 人の生命、身体または財産の保護のために必要な場合<br>
    (３) 公衆衛生の向上または児童の健全育成の推進に必要がある場合<br>
    (４) 国の機関もしくは地方公共団体またはその委託を受けた者が法令の定める事務を遂行することに対応して協力する必要がある場合</p>
