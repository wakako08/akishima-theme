<div class="about-charter__block">
    <p><strong>（表彰規定）</strong><br>
    第10条　本会の会員で次の条項に該当する場合は常任委員会の決定に基づき表彰する。<br>
    (１) 本会の運営に献身的努力をした方<br>
    (２) その他常任役員会で必要と認めた方<br>
    (３) 加盟自治会で、通算し７年以上となる一般役員の方<br>
    ２　次の条項に該当する場合は、市の表彰規定により表彰されるため、本会として市に対して申請するものとする。<br>
    (１) 本会役員ならびに加盟自治会の会長、副会長、会計の職にある期間を通算した場合における職務期間が５年以上となる方<br>
    (２) 前項で、５年ごとにその対象者となる方<br>
    第11条　本規程により表彰をすべき団体及び個人があるときは、表彰推薦書を常任委員および事務局が作成し、会長へ提出する。会長は三役会に諮り、常任委員会で承認を得る。</p>
    <p><strong>（慶弔見舞に関する規定）</strong><br>
    第12条　本会委員が死亡した際、生花を本会の名義で出す。<br>
    ２　現役の自治会長が死亡した際、会長名で感謝状を出す。<br>
    ３　会長が必要と判断する場合は、生花、弔電等を三役に諮り行うことが出来る。<br>
    ４　その他の場合は、本会としては行わない。</p>
    <p><strong>（団体保険加入と保険金支払いに関する規定）</strong><br>
    第13条　本会主催の行事の際、常任委員会に報告後必要に応じ団体保険の加入手続きを行う。<br>
    ２　保険金の支払いについては、事務局で当事者と連携をとり、保険規定に従って手続きをとり保険金の支払いをする。</p>
    <p><strong>（会計に関する規定）</strong><br>
    第14条　本会の運営費は、銀行口座を作成し預けて運用する。<br>
    ２　印鑑は会長、通帳は会計が保管する。<br>
    ３　会計は、次の任務を負う。<br>
    (１) 現金、預金の管理<br>
    (２) 予算に基づく運用計画と出納業務<br>
    (３) 決算書類の作成<br>
    (４) その他行事等による会計実務全般<br>
    ４　会計は、総会で議決された予算にもとづいて行う。<br>
    ５　予算は、次年度の活動方針を基礎として、計上された額をもとに、委員会別に作成する。事業計画策定委員会が担当、常任委員会で審議し、総会の議決に付す。<br>
    ６　金銭の支出は伝票(第３様式)を用いる。また、研修会参加等で交通費を出金する場合は出金伝票を用いる。<br>
    (１) 伝票には、会計、該当委員長および会長の押印を要する<br>
    (２) 出納処理事項はすべて帳簿に記録する<br>
    (３) 支出は、領収書または請求書に基づき会計が出金伝票を作成し、該当委員会の委員長および会長の承認を得て支払う<br>
    (４) 大口予算出金の流れは次のように行う<br>
    　①事前に「事業計画起案書」を作成し、常任委員会の承認を得るものとする。また、緊急を要する場合は会長が「事業計画起案書」の内容を確認し、三役の承諾を得る<br>
    　②会計は委員長の請求により出金し委員長に預ける(出金伝票を使用)。振込の場合は、その金額を除き現金を準備する<br>
    　③行事等終了後、速やかに精算し領収書・請求書・残金をまとめ、会計に渡す<br>
    　④出金伝票に精算金額を領収書単位に記入し、会計が金額を確認後、委員長、会長が押印し終了とする<br>
    (５) 小口予算出金の流れは次のように行う<br>
    　①委員長の決済で予算内で出金できる（5,000円以上は会長に承認を得る）<br>
    　②出金伝票と領収書で精算業務をする<br>
    ７　毎年度末にすべての会計帳簿を締切り、決算報告書を作成する。<br>
    ８　会計は、監事に決算報告書を提出し、監査を受けなければならない。<br>
    ９　監査を受けた決算報告書は、常任委員会で確認し、総会の承認を受けなければならない。<br>
    10　監査は、一年間に２回(原則１０月、４月)行うものとする。ただし、監事の判断で定期以外に行うことができる。監事は、監査に必要な書類の提出や常任委員会に出席し意見を述べることができる。<br>
    11　監査は次の事項について行う。<br>
    (１) 予算執行の適否<br>
    (２) 諸経費の適否<br>
    (３) 帳簿記載・伝票整理の適否<br>
    (４) 現金および預貯金残高の確認<br>
    (５) 常任委員会の運営<br>
    (６) 総会時に、前年度の会計、業務監査報告<br>
    (７) その他必要と認められた事項<br>
    12　監事は、監査の都度、常任委員会に文書を以て総会前に、会計の決算書と同時にその結果を報告する。</p>
