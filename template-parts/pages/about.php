    <p><strong>（目　的）</strong><br>
    この基準は、昭島市自治会連合会（以下「本会」という。）規約第４条の規程に定める事業を円滑に行うため、本会の活動について必要な事項を定めるものとする。</p>
    <p><strong>（事務局）</strong><br>
    事務局は、昭島市市民部生活コミュニティ課に担当していただき、円滑な運営をする。</p>
    <p><strong>（加入と退会）</strong><br>
    本会に加入を希望する自治会は書面(第１号様式)をもって次に掲げる事項を会長に提出し、常任委員会の承認を持って、会員となる。<br>
    ２　記載事項は、①自治会の名称、②自治会の区域図、③班数、④加入世帯数、⑤代表者及び役員の氏名、住所、連絡先、⑥自治会規約とする。<br>
    ３　諸事情で本会を退会することになった自治会は、退会届(第２号様式)を会長に提出し、常任委員会への報告後、退会する。</p>
    <p><strong>（本会組織ブロックと地域割り）</strong><br>
    加盟自治会を区分けしてブロックを組織し、連合会規約の別表１に定め、更に自治連を６分割の中学校エリアとし行政との協議単位とする。</p>
</div>

<div class="about-charter__block">
    <p><strong>（本会としての事業の取り組み内容）</strong><br>
    本会として、次の事業に取り組み、各委員会で分担し執行する。<br>
    (１) 自治会加入促進に関すること<br>
    (２) 地域防災への取組みに関すること<br>
    (３) 加盟自治会の活動支援と地域コミュニティに関すること<br>
    (４) 本会主催行事の開催に関すること<br>
    (５) 自治会活動に資する研修会等の開催に関すること<br>
    (６) 本会機関紙の編集、発行に関すること<br>
    (７) 市行政についての周知および協力に関すること<br>
    (８) 同一目的を有する団体との協力連携に関すること<br>
    (９) その他本会目的の達成に必要な事項に関すること</p>
    <p><strong>（委員会組織及び事業内容）</strong><br>
    本会として運営上、年間を通して必要な委員会として、加入促進委員会、地域防災委員会、総務企画委員会の３つを常任委員会の中に設置する。<br>
    ２　委員会の設置と正副委員長案を、会長は三役会に諮り、常任委員会の承認を得る。<br>
    ３　委員会は１０名前後とし、任期は１年とし次の者で構成する。<br>
    　・本会役員(委員会兼務可)<br>
    　・会長が推薦する者<br>
    ４　次年度の事業内容は、事業計画策定委員会にて協議し、常任委員会の承認を得る。</p>
    <p><strong>（専門委員会の設置）</strong><br>
    常任委員会は必要に応じて、専門委員会として役員選挙運営委員会、事業計画策定委員会を設置することができる。また、本会の事業を円滑に行うため、常任委員会の承認を受け、新たな専門委員会を設置することができる。ただし、その目的の達成をもって解散する。</p>
    <p><strong>（役員選挙運営委員会）</strong><br>
    第８条　役員選挙運営委員会は、事務局の協力を得て総務企画委員会が担当する。<br>
    ２　会長、副会長の選出に関しては「会長・副会長推薦委員会」を設置し次の内容を２月の常任委員会で選出する。<br>
    「会長・副会長推薦委員会」で会長、副会長２名を選出し、常任委員会に報告し承認を受ける。副会長残り１名は３月常任委員会にて会長候補が指名し承認を得る。<br>
    会長・副会長推薦委員６名選出の選挙権は、常任委員(ブロック長)のみが有する。<br>
    推薦委員は市内全域から均等に３つの地区から自薦又は他薦で各２名を選出する。<br>
    東地区　1,2,3,4,5,6,(21)のブロック<br>
    中地区　7,8,9,15,16,17,19,20ブロック<br>
    西地区　10,11,12,13,14,16,18ブロック<br>
    ３　「会長・副会長推薦委員会」委員６名は別室に移動し、会長、副会長２名の候補者を選ぶ。委員会の進行役は役員選挙運営委員会の総務企画委員長が行うものとする。<br>
    (１) 会長、副会長の被選挙権は、会長は２年、副会長は１年以上経験した本会役員が有するが本人の健康等も考慮し選出する。年齢制限は、特にこれを設けないものとする。<br>
    (２) 会長、副会長の任期は２年とし、会長は業務が多岐にわたるため、専任とする。<br>
    (３) 会計、監事各２名の人選は本会役員から、会長、副会長候補者で協議し、３月の常任委員会に報告し承認を受ける。総会の承認後、委嘱状を会長名で発行し授与する。任期は１年とする。<br>
    ４　相談役、委員は総会にて報告後、委嘱状を会長名で発行し授与する。監事も含め、該当ブロック長宛に通知する。</p>
    <p><strong>（事業計画策定委員会）</strong><br>
    第９条　事業計画策定委員は三役、３つの委員会から１名ずつ、会長が指名し招集することができる。<br>
    ２　委員長は、会長が務めるものとする。<br>
    ３　次年度の事業方針および事業計画、予算に関する事項を策定する。</p>
